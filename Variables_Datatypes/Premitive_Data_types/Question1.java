package Variables_Datatypes.Premitive_Data_types;


public class Question1 {
    public static void main(String[] args) {

        byte age = 20;
        short year = 2026;
        int salary = 50000;
        long population = 1400000000L;

        float height = 5.8f;
        double price = 999.99;

        char grade = 'A';
        boolean passed = true;

        System.out.println("Byte value: " + age);
        System.out.println("Short value: " + year);
        System.out.println("Int value: " + salary);
        System.out.println("Long value: " + population);
        System.out.println("Float value: " + height);
        System.out.println("Double value: " + price);
        System.out.println("Char value: " + grade);
        System.out.println("Boolean value: " + passed);
    }
}